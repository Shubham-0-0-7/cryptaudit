//! Findings that depend on the whole crate, not one file.

use std::path::Path;

use cryptaudit::{ScanOptions, scan};

const COMPARE: &str = "use hmac::{Hmac, Mac};\nuse sha2::Sha256;\n\
fn verify(key: &[u8], msg: &[u8], expected: &Tag) -> bool {\n\
    let mut mac = Hmac::<Sha256>::new_from_slice(key).unwrap();\n\
    mac.update(msg);\n\
    mac.finalize() == *expected\n}\n";
const RAW: &str = "use hmac::{Hmac, Mac};\nuse sha2::Sha256;\n\
fn verify(key: &[u8], msg: &[u8], expected: &[u8]) -> bool {\n\
    let mut mac = Hmac::<Sha256>::new_from_slice(key).unwrap();\n\
    mac.update(msg);\n\
    mac.finalize().into_bytes().as_slice() == expected\n}\n";
const CT_TYPE_EQUAL_CT: &str = "impl PartialEq for Tag {\n    fn eq(&self, other: &Self) -> bool {\n        equal_ct(&self.0, &other.0)\n    }\n}\n";
const CT_TYPE: &str = "impl PartialEq for Tag {\n    fn eq(&self, other: &Self) -> bool {\n        self.0.ct_eq(&other.0).into()\n    }\n}\n";

fn confidences(name: &str, files: &[(&str, &str)]) -> Vec<String> {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join("ctx")
        .join(name);
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(dir.join("src")).unwrap();
    for (n, s) in files {
        std::fs::write(dir.join("src").join(n), s).unwrap();
    }
    let report = scan(
        &dir,
        &ScanOptions {
            include_tests: false,
            config: None,
            suppress: false,
        },
    );
    report
        .findings
        .iter()
        .filter(|f| f.rule == "CA021")
        .map(|f| f.confidence.to_string())
        .collect()
}

#[test]
fn tag_compare_is_reported_without_a_constant_time_type() {
    assert_eq!(confidences("plain", &[("lib.rs", COMPARE)]), ["high"]);
}

#[test]
fn tag_compare_is_low_when_the_crate_defines_constant_time_eq() {
    let got = confidences("ct", &[("lib.rs", COMPARE), ("tag.rs", CT_TYPE)]);
    assert_eq!(got, ["low"]);
}

#[test]
fn constant_time_helper_with_another_name_counts() {
    let got = confidences("ct2", &[("lib.rs", COMPARE), ("tag.rs", CT_TYPE_EQUAL_CT)]);
    assert_eq!(got, ["low"]);
}

#[test]
fn raw_byte_compare_stays_reported_in_such_a_crate() {
    let got = confidences("raw", &[("lib.rs", RAW), ("tag.rs", CT_TYPE)]);
    assert_eq!(got, ["high"]);
}

#[test]
fn out_of_line_test_modules_and_generated_files_are_skipped() {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join("ctx")
        .join("skip");
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(dir.join("src")).unwrap();
    std::fs::write(
        dir.join("src/lib.rs"),
        "#[cfg(test)]\nmod helpers;\nmod real;\n",
    )
    .unwrap();
    std::fs::write(dir.join("src/helpers.rs"), RAW).unwrap();
    std::fs::write(dir.join("src/real.rs"), RAW).unwrap();
    std::fs::write(
        dir.join("src/api.rs"),
        format!("// @generated by openapi\n{RAW}"),
    )
    .unwrap();
    let report = scan(
        &dir,
        &ScanOptions {
            include_tests: false,
            config: None,
            suppress: false,
        },
    );
    let paths: Vec<_> = report
        .findings
        .iter()
        .map(|f| f.path.file_name().unwrap().to_string_lossy().into_owned())
        .collect();
    assert_eq!(paths, ["real.rs"]);
}

#[test]
fn test_support_directories_and_files_are_skipped() {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join("ctx")
        .join("testwords");
    let _ = std::fs::remove_dir_all(&dir);
    for sub in [
        "src/tests_and_kats",
        "src/test_utils",
        "src/latest",
        "testbench/src",
    ] {
        std::fs::create_dir_all(dir.join(sub)).unwrap();
    }
    for file in [
        "src/tests_and_kats/a.rs",
        "src/test_utils/b.rs",
        "src/benchmark.rs",
        "src/interop_test_vectors.rs",
        "src/latest/c.rs",
        "testbench/src/d.rs",
        "src/real.rs",
    ] {
        std::fs::write(dir.join(file), RAW).unwrap();
    }
    let report = scan(
        &dir,
        &ScanOptions {
            include_tests: false,
            config: None,
            suppress: false,
        },
    );
    let mut paths: Vec<_> = report
        .findings
        .iter()
        .map(|f| f.path.file_name().unwrap().to_string_lossy().into_owned())
        .collect();
    paths.sort();
    assert_eq!(paths, ["c.rs", "real.rs"]);
}

#[test]
fn build_scripts_are_not_scanned() {
    // A build script checks a download on the developer's machine; no attacker is
    // guessing the checksum byte by byte.
    assert!(confidences("build_script", &[("build.rs", COMPARE)]).is_empty());
}

/// Writes `files` (path, contents) under a fresh directory and returns the CA024
/// confidences by file name.
fn weak_primitive(name: &str, files: &[(&str, &str)]) -> Vec<(String, String)> {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join("ctx")
        .join(name);
    let _ = std::fs::remove_dir_all(&dir);
    for (n, s) in files {
        let path = dir.join(n);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, s).unwrap();
    }
    let report = scan(
        &dir,
        &ScanOptions {
            include_tests: false,
            config: None,
            suppress: false,
        },
    );
    let mut out: Vec<_> = report
        .findings
        .iter()
        .filter(|f| f.rule == "CA024")
        .map(|f| {
            (
                f.path.file_name().unwrap().to_string_lossy().into_owned(),
                f.confidence.to_string(),
            )
        })
        .collect();
    out.sort();
    out
}

const CHOOSES_RC4: &str = "fn handshake(key: &[u8]) { let c = Rc4::new(key); }\n";
const OFFERS_TDES: &str = "pub enum AlgorithmId { Aes128, Tdes }\n";

#[test]
fn a_program_that_picks_a_broken_cipher_is_reported() {
    let got = weak_primitive(
        "weak_app",
        &[("Cargo.toml", ""), ("src/lib.rs", CHOOSES_RC4)],
    );
    assert_eq!(got, [("lib.rs".to_string(), "medium".to_string())]);
}

#[test]
fn a_crate_declaring_the_primitive_is_low_in_every_file() {
    let got = weak_primitive(
        "weak_lib",
        &[
            ("Cargo.toml", ""),
            ("src/ids.rs", OFFERS_TDES),
            ("src/mac.rs", CHOOSES_RC4),
        ],
    );
    assert_eq!(got, [("mac.rs".to_string(), "low".to_string())]);
}

#[test]
fn the_library_does_not_excuse_the_application_next_to_it() {
    let got = weak_primitive(
        "weak_workspace",
        &[
            ("lib/Cargo.toml", ""),
            ("lib/src/ids.rs", OFFERS_TDES),
            ("app/Cargo.toml", ""),
            ("app/src/main.rs", CHOOSES_RC4),
        ],
    );
    assert_eq!(got, [("main.rs".to_string(), "medium".to_string())]);
}
